// npm run seed:sql — writes supabase/seed.sql from /seed/*.json. Paste the
// output into the Supabase SQL Editor. Safe to re-run: existing rows are left
// alone, so flags and ratings survive.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SeedFileSchema } from "@/lib/schemas";

type Value = string | number | boolean | null | undefined | string[];

function literal(value: Value): string {
  if (value === null || value === undefined) return "null";
  if (Array.isArray(value)) return `array[${value.map(literal).join(", ")}]::text[]`;
  if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`;
  return String(value);
}

function insert(table: string, row: Record<string, Value>): string {
  const columns = Object.keys(row).join(", ");
  const values = Object.values(row).map(literal).join(",\n  ");
  return `insert into ${table} (${columns}) values (\n  ${values}\n) on conflict (id) do nothing;`;
}

const dir = join(process.cwd(), "seed");
const statements: string[] = [];

for (const file of readdirSync(dir).filter((name) => name.endsWith(".json")).sort()) {
  const { bank, cards, quizzes, generation } = SeedFileSchema.parse(
    JSON.parse(readFileSync(join(dir, file), "utf8")),
  );
  statements.push(
    insert("banks", {
      id: bank.id,
      title: bank.title,
      subject: bank.subject,
      level: bank.level,
      tags: bank.tags,
      license: bank.license,
      attribution: bank.attribution,
      source_url: bank.sourceUrl,
      origin: bank.origin,
      source_text: bank.sourceText,
      ratings_up: bank.ratingsUp,
      ratings_down: bank.ratingsDown,
      created_at: bank.createdAt,
    }),
  );
  for (const card of cards) {
    statements.push(
      insert("cards", {
        id: card.id,
        bank_id: card.bankId,
        topic: card.topic,
        title: card.title,
        body: card.body,
        quote: card.quote,
        source_start: card.sourceStart,
        source_end: card.sourceEnd,
        verified: card.verified,
        flags: card.flags,
        '"order"': card.order,
      }),
    );
  }
  for (const quiz of quizzes) {
    statements.push(
      insert("quizzes", {
        id: quiz.id,
        bank_id: quiz.bankId,
        topic: quiz.topic,
        question: quiz.question,
        options: quiz.options,
        answer_index: quiz.answerIndex,
        explanation: quiz.explanation,
      }),
    );
  }
  if (generation) {
    statements.push(
      insert("generations", {
        id: generation.id,
        bank_id: generation.bankId,
        model: generation.model,
        input_tokens: generation.inputTokens,
        output_tokens: generation.outputTokens,
        cost_usd: generation.costUsd,
        duration_ms: generation.durationMs,
        cards_total: generation.cardsTotal,
        cards_verified: generation.cardsVerified,
        created_at: generation.createdAt,
      }),
    );
  }
}

const header = "-- Generated by npm run seed:sql from /seed/*.json. Do not edit by hand.\n";
const output = `${header}begin;\n\n${statements.join("\n\n")}\n\ncommit;\n`;
writeFileSync(join(process.cwd(), "supabase", "seed.sql"), output);
console.log(`Wrote supabase/seed.sql (${statements.length} rows)`);
